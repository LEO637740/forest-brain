// Run explicitly with a downloaded Natural Earth 110m countries GeoJSON path.
// The generated module is committed with the app; no download runs at startup/build.
import {readFileSync,writeFileSync} from 'node:fs';
import {projectPoint} from '../src/workspace/spatial/geoMapModel.ts';

const world=JSON.parse(readFileSync(process.argv[2],'utf8'));
const china=JSON.parse(readFileSync(new URL('../public/assets/geo/china-provinces.json',import.meta.url),'utf8'));
function simplify(points,tolerance=.0008){
  if(points.length<=4)return points;
  const first=points[0],last=points.at(-1),dx=last.x-first.x,dy=last.y-first.y,length=dx*dx+dy*dy;
  let furthest=0,index=0;
  for(let i=1;i<points.length-1;i++){
    const point=points[i],t=length?Math.max(0,Math.min(1,((point.x-first.x)*dx+(point.y-first.y)*dy)/length)):0;
    const distance=(point.x-first.x-t*dx)**2+(point.y-first.y-t*dy)**2;
    if(distance>furthest){furthest=distance;index=i;}
  }
  if(furthest>tolerance*tolerance)return [...simplify(points.slice(0,index+1),tolerance).slice(0,-1),...simplify(points.slice(index),tolerance)];
  return [first,last];
}
const shapes=[];
for(const [kind,collection] of [['country',world],['province',china]]){
  for(const feature of collection.features){
    if(!['Polygon','MultiPolygon'].includes(feature.geometry?.type))continue;
    const p=feature.properties,polygons=feature.geometry.type==='Polygon'?[feature.geometry.coordinates]:feature.geometry.coordinates;
    polygons.forEach((polygon,index)=>{
      const rings=polygon.map(ring=>simplify(ring.map(([longitude,latitude])=>projectPoint({longitude,latitude},0)))).filter(ring=>ring.length>=4);
      if(!rings.length)return;
      const points=rings.flat(),xs=points.map(point=>point.x),ys=points.map(point=>point.y);
      const number=n=>Number(n.toFixed(6));
      shapes.push({id:`${kind}:${p.ADM0_A3??p.adcode}:${index}`,kind,
        bounds:[Math.min(...xs),Math.min(...ys),Math.max(...xs),Math.max(...ys)].map(number),
        path:rings.map(ring=>ring.map((point,i)=>`${i?'L':'M'}${number(point.x)},${number(point.y)}`).join('')+'Z').join('')});
    });
  }
}
const destination=new URL('../src/workspace/spatial/localBasemapData.ts',import.meta.url);
writeFileSync(destination,'// Generated by scripts/prepare-local-basemap.mjs. Sources: public/assets/geo/SOURCES.md\nexport const BASEMAP_SHAPES: {id:string;kind:string;bounds:number[];path:string}[] = '+JSON.stringify(shapes)+';\n');
console.log(JSON.stringify({shapes:shapes.length,bytes:readFileSync(destination).byteLength}));
